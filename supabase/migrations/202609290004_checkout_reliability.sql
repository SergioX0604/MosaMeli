   and pago_declarado is null;

create table if not exists public.pedido_historial (
  id bigint generated by default as identity primary key,
  pedido_id bigint not null references public.pedidos(id) on delete cascade,
  estado_anterior text,
  estado_nuevo text not null,
  cambiado_por uuid,
  fecha timestamptz not null default now()
);

create index if not exists pedido_historial_pedido_fecha_idx
  on public.pedido_historial (pedido_id, fecha desc);

alter table public.pedido_historial enable row level security;
revoke all on table public.pedido_historial from anon, authenticated;
grant select on table public.pedido_historial to authenticated;

drop policy if exists pedido_historial_select_own_or_admin on public.pedido_historial;
create policy pedido_historial_select_own_or_admin
  on public.pedido_historial for select
  to authenticated
  using (
    public.is_admin() or exists (
      select 1 from public.pedidos p
       where p.id = pedido_id and p.usuario_id = auth.uid()
    )
  );

create table if not exists public.notificaciones_pendientes (
  id bigint generated by default as identity primary key,
  pedido_id bigint not null references public.pedidos(id) on delete cascade,
  tipo text not null check (tipo in ('confirmacion', 'estado')),
  intentos integer not null default 0 check (intentos >= 0),
  siguiente_intento timestamptz not null default now(),
  ultimo_error text,
  completada_en timestamptz,
  creada_en timestamptz not null default now(),
  unique (pedido_id, tipo, completada_en)
);

create index if not exists notificaciones_pendientes_reintento_idx
  on public.notificaciones_pendientes (siguiente_intento)
  where completada_en is null;

alter table public.notificaciones_pendientes enable row level security;
revoke all on table public.notificaciones_pendientes from anon, authenticated;

create or replace function public.cotizar_delivery(
  p_lat double precision,
  p_lng double precision,
  p_momento timestamptz default now()
)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_distancia double precision;
  v_base numeric;
  v_nocturno numeric := 0;
  v_domingo numeric := 0;
  v_hora integer;
  v_dia integer;
  origin_lat constant double precision := -11.9726;
  origin_lng constant double precision := -76.7790;
begin
  if p_lat is null or p_lng is null or p_lat < -90 or p_lat > 90 or p_lng < -180 or p_lng > 180 then
    raise exception 'UBICACION_INVALIDA';
  end if;

  v_distancia := 6371 * 2 * asin(sqrt(
    power(sin(radians(p_lat - origin_lat) / 2), 2) +
    cos(radians(origin_lat)) * cos(radians(p_lat)) *
    power(sin(radians(p_lng - origin_lng) / 2), 2)
  ));

  if v_distancia > 10 then
    raise exception 'FUERA_DE_COBERTURA';
  end if;

  v_base := case
    when v_distancia <= 2 then 5
    when v_distancia <= 4 then 7
    when v_distancia <= 7 then 10
    else 15
  end;

  v_hora := extract(hour from p_momento at time zone 'America/Lima');
  v_dia := extract(dow from p_momento at time zone 'America/Lima');
  if v_hora >= 20 or v_hora < 7 then v_nocturno := 3; end if;
  if v_dia = 0 then v_domingo := 2; end if;

  return jsonb_build_object(
    'distancia', round(v_distancia::numeric, 2),
    'base', v_base,
    'recargo_nocturno', v_nocturno,
    'recargo_domingo', v_domingo,
    'costo', v_base + v_nocturno + v_domingo
  );
end;
$$;

revoke all on function public.cotizar_delivery(double precision, double precision, timestamptz) from public;
grant execute on function public.cotizar_delivery(double precision, double precision, timestamptz) to anon, authenticated;

create or replace function public.liberar_stock_pedido(p_pedido_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.pedidos%rowtype;
  v_item record;
begin
  select * into v_order from public.pedidos where id = p_pedido_id for update;
  if not found or v_order.stock_liberado_en is not null then return; end if;

  for v_item in
    select (item ->> 'id')::bigint as id,
           sum((item ->> 'cantidad')::integer)::integer as cantidad
      from jsonb_array_elements(v_order.items) item
     group by (item ->> 'id')::bigint
  loop
    update public.productos set stock = stock + v_item.cantidad where id = v_item.id;
  end loop;

  update public.pedidos set stock_liberado_en = now() where id = p_pedido_id;
end;
$$;

revoke all on function public.liberar_stock_pedido(bigint) from public, anon, authenticated;

create or replace function public.expirar_reservas()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order record;
  v_count integer := 0;
begin
  for v_order in
    select id, estado from public.pedidos
     where estado = 'pedido_recibido'
       and pago_declarado is null
       and stock_liberado_en is null
       and reserva_expira_en <= now()
     for update skip locked
  loop
    perform public.liberar_stock_pedido(v_order.id);
    update public.pedidos set estado = 'cancelado' where id = v_order.id;
    insert into public.pedido_historial (pedido_id, estado_anterior, estado_nuevo)
    values (v_order.id, v_order.estado, 'cancelado');
    v_count := v_count + 1;
  end loop;
  return v_count;
end;
$$;

revoke all on function public.expirar_reservas() from public, anon;
grant execute on function public.expirar_reservas() to authenticated;

create or replace function public.registrar_notificacion_pendiente(
  p_pedido_id bigint,
  p_tipo text,
  p_error text default null
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if p_tipo not in ('confirmacion', 'estado') then raise exception 'TIPO_INVALIDO'; end if;
  if not exists (
    select 1 from public.pedidos
     where id = p_pedido_id
       and (usuario_id = auth.uid() or public.is_admin())
  ) then raise exception 'PEDIDO_NO_ENCONTRADO'; end if;

  insert into public.notificaciones_pendientes (pedido_id, tipo, ultimo_error)
  values (p_pedido_id, p_tipo, left(coalesce(p_error, ''), 500));
end;
$$;

revoke all on function public.registrar_notificacion_pendiente(bigint, text, text) from public, anon;
